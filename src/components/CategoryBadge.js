// Normaliza o nome da categoria para casar com o mapa de ícones
// (minúsculas, sem acentos).
function normalize(name) {
  return (name || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

