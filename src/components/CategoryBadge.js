export function getCategoryIcon(name) {
  return CATEGORY_ICONS[normalize(name)] || FALLBACK_ICON;
}

export default function CategoryBadge({ id, name, color, className = '' }) {
  const content = (
    <>
      <svg
        className="w-3 h-3 flex-shrink-0"
        fill="none"
        stroke="currentColor"
        viewBox="0 0 24 24"
        strokeWidth="2"
        aria-hidden="true"
      >
        {getCategoryIcon(name)}
      </svg>
      <span className="truncate">{name}</span>
    </>
  );

  const classes = `inline-flex items-center gap-1.5 text-xs text-white px-2.5 py-1 rounded-md font-semibold max-w-full ${className}`;

  if (id == null) {
    return <span className={classes} style={{ backgroundColor: color }}>{content}</span>;
  }

  return (
    <Link to={`/category/${id}`} className={`${classes} transition hover:opacity-90`} style={{ backgroundColor: color }}>
      {content}
    </Link>
  );
}
